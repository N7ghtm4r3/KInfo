package com.tecknobit.kinfo.operatingsystem

import com.tecknobit.kinfo.model.desktop.common.operatingsystem.processes.OSThread
import com.tecknobit.kinfo.model.desktop.common.operatingsystem.processes.State
import com.tecknobit.kinfo.model.desktop.macos.operatingsystem.MacOsOSProcess

/**
 * The `MacOsOsProcessImpl` class is useful to provide information about a macOS process
 *
 * @property name The name of the process
 * @property path The path to the process executable
 * @property commandLine The command line used to start the process
 * @property arguments The arguments of the process
 * @property environmentVariables The environment variables of the process
 * @property currentWorkingDirectory The current working directory of the process
 * @property user The name of the user running the process
 * @property userId The identifier of the user running the process
 * @property group The name of the group associated with the process
 * @property groupId The identifier of the group associated with the process
 * @property state The current state of the process
 * @property processId The identifier of the process
 * @property parentProcessId The identifier of the parent process
 * @property threadCount The number of threads owned by the process
 * @property priority The priority of the process
 * @property virtualSize The virtual memory size of the process in bytes
 * @property residentMemory The resident memory used by the process in bytes
 * @property privateResidentMemory The private resident memory used by the process in bytes
 * @property kernelTime The time spent by the process in kernel mode in milliseconds
 * @property userTime The time spent by the process in user mode in milliseconds
 * @property startTime The process start time in milliseconds since the Unix epoch
 * @property bytesRead The number of bytes read by the process
 * @property bytesWritten The number of bytes written by the process
 * @property openFiles The number of files opened by the process
 * @property softOpenFileLimit The soft limit on the number of open files
 * @property hardOpenFileLimit The hard limit on the number of open files
 * @property processCpuLoadCumulative The cumulative CPU load of the process
 * @property processCpuLoadBetweenTicks The CPU load of the process between ticks
 * @property bitness The bitness of the process
 * @property affinityMask The CPU affinity mask of the process
 * @property threadDetails The details of the threads owned by the process
 * @property minorFaults The number of minor page faults generated by the process
 * @property majorFaults The number of major page faults generated by the process
 * @property contextSwitches The total number of context switches performed by the process
 * @property voluntaryContextSwitches The number of voluntary context switches performed by the process
 * @property involuntaryContextSwitches The number of involuntary context switches performed by the process
 *
 * @author N7ghtm4r3 - Tecknobit
 *
 * @see MacOsOSProcess
 *
 * @since 1.1.0
 */
data class MacOsOsProcessImpl(
    override val name: String,
    override val path: String,
    override val commandLine: String,
    override val arguments: List<String>,
    override val environmentVariables: Map<String, String>,
    override val currentWorkingDirectory: String,
    override val user: String,
    override val userId: String,
    override val group: String,
    override val groupId: String,
    override val state: State,
    override val processId: Int,
    override val parentProcessId: Int,
    override val threadCount: Int,
    override val priority: Int,
    override val virtualSize: Long,
    override val residentMemory: Long,
    override val privateResidentMemory: Long,
    override val kernelTime: Long,
    override val userTime: Long,
    override val startTime: Long,
    override val bytesRead: Long,
    override val bytesWritten: Long,
    override val openFiles: Long,
    override val softOpenFileLimit: Long,
    override val hardOpenFileLimit: Long,
    override val processCpuLoadCumulative: Double,
    override val processCpuLoadBetweenTicks: Double,
    override val bitness: Int,
    override val affinityMask: Long,
    override val threadDetails: List<OSThread>,
    override val minorFaults: Long,
    override val majorFaults: Long,
    override val contextSwitches: Long,
    override val voluntaryContextSwitches: Long,
    override val involuntaryContextSwitches: Long
) : MacOsOSProcess {

    /**
     * `updateAttributes` whether updating the process attributes is supported
     *
     * This value is `false` because this implementation represents a native process snapshot
     */
    override val updateAttributes: Boolean = false

}
